import { CraftingStationId, RecipeDef } from '@/types/game';

let rIdx = 0;
const r = (
  resultId: string,
  resultCount: number,
  ingredients: [string, number][],
  station: CraftingStationId = 'hand',
  hardmodeOnly = false
): RecipeDef => ({
  id: `recipe_${++rIdx}_${resultId}`,
  resultId,
  resultCount,
  ingredients: ingredients.map(([itemId, count]) => ({ itemId, count })),
  station,
  hardmodeOnly,
});

